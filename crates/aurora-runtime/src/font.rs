/// The five columns of `c`, or `None` for anything outside printable ASCII.
///
/// Unprintable characters draw nothing rather than a box: a control code in a
/// string is a bug in the string, and a row of boxes is harder to read than a
/// gap when you are trying to find it.
pub fn glyph(c: u8) -> Option<&'static [u8; 5]> {
    if c < FIRST || c > 126 {
        return None;
    }
    GLYPHS.get((c - FIRST) as usize)
}

/// Advance of one glyph at `scale`, including the gap after it.
pub fn advance(scale: i64) -> i64 {
    (GLYPH_W + GLYPH_GAP) * scale.max(1)
}

/// Whole-pixel scale for a requested pixel height. At least 1, so text asked
/// for smaller than the font never vanishes - it is drawn at 7px instead.
pub fn scale_for(px: i64) -> i64 {
    (px / GLYPH_H).max(1)
}

/// Width of `text` at `scale`, in pixels, with no trailing gap.
pub fn width(text: &str, scale: i64) -> i64 {
    let n = text.chars().count() as i64;
    if n == 0 {
        return 0;
    }
    n * advance(scale) - GLYPH_GAP * scale.max(1)
}

/// Call `put(x, y)` for every lit pixel of `text` drawn at `(x0, y0)`.
///
/// The caller owns clipping and colour: this crate's framebuffer and the 3D
/// overlay both want the same glyphs and neither wants the other's bounds
/// check. Returns the x it finished at.
pub fn blit(x0: i64, y0: i64, text: &str, scale: i64, mut put: impl FnMut(i64, i64)) -> i64 {
    let s = scale.max(1);
    let mut x = x0;
    for ch in text.chars() {
        let byte = if ch.is_ascii() { ch as u8 } else { b'?' };
        if let Some(cols) = glyph(byte) {
            for (cx, col) in cols.iter().enumerate() {
                for row in 0..GLYPH_H {
                    if col & (1 << row) != 0 {
                        for dy in 0..s {
                            for dx in 0..s {
                                put(x + cx as i64 * s + dx, y0 + row * s + dy);
                            }
                        }
                    }
                }
            }
        }
        x += advance(s);
    }
    x
}

