//! A font that ships with the engine.
//!
//! `draw_text` used to need `load_font` and a TTF on disk, and drew NOTHING -
//! silently - when there was none. A game engine you cannot print a word with
//! until you have sourced a font file is missing a primitive, and "silently"
//! makes it worse: a HUD that renders no text looks identical to a HUD whose
//! text is off-screen, the wrong colour, or behind something.
//!
//! So there is a font in the binary. 5x7 glyphs for printable ASCII, scaled by
//! whole pixels, which suits a low-poly game and cannot go blurry. `load_font`
//! still overrides it for anyone who wants real type.
//!
//! Each glyph is five columns; bit 0 of a column is its TOP row. Generated from
//! a legible ASCII-art spec rather than typed as hex - the spec is what a human
//! should edit, and `a_glyph_matches_its_spec` pins two of them so a bad
//! regeneration cannot land quietly.

/// Columns per glyph, before spacing.
pub const GLYPH_W: i64 = 5;
/// Rows per glyph.
pub const GLYPH_H: i64 = 7;
/// Blank columns between glyphs, in glyph pixels.
pub const GLYPH_GAP: i64 = 1;
/// The first character the table covers.
pub const FIRST: u8 = 32;

